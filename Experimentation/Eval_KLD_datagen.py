def string2bool(s: str) -> bool:
    """
    Convert a string to a boolean.
    Args:
    s: str: the string to convert
    Returns:
    bool: the boolean value
    """
    if s.lower() in ["true", "1"]:
        return True
    elif s.lower() in ["false", "0"]:
        return False
    else:
        raise ValueError(f"String {s} not recognized as boolean!")

class Eval_KLD_datagen():
    """
    Class to determine the KLD between the data generated by two different setups.
    """

    def __init__(
            self, 
            base_config_path: str,
            config_param_to_change: str,
            config_param_value1: float,
            config_param_value2: float,
            n_samples: int = 1000
    ):
        self.config_path = base_config_path
        self.config = configparser.ConfigParser() # Create a ConfigParser object
        
        self.config.read(f"{self.config_path}")

        self.config_param_to_change = config_param_to_change
        self.config_param_value1 = config_param_value1
        self.config_param_value2 = config_param_value2
        self.n_samples = n_samples


    def sample_for_value(self, value):

        gen_config = self.config["DATA_GENERATION"]
        N_EPOCHS = int(self.config["BASIC"]["N_epochs"])
        N_BATCHES_PER_EPOCH = int(self.config["BASIC"]["N_batches_per_epoch"])
        BATCH_SIZE = self.n_samples*2
        P = int(self.config["BASIC"]["P"])
        N = int(self.config["BASIC"]["N"])
        N_SAMPLES_PER_EPOCH = int(self.config["BASIC"]["N_samples_per_epoch"])

        pprogram_params = ast.literal_eval(gen_config["pprogram_params"])

        pprogram_params[config_param_to_change] = value

        self.curriculum = Curriculum(max_iter=int(N_EPOCHS*N_BATCHES_PER_EPOCH*BATCH_SIZE*0.5))
        param_list = [(name, self.curriculum.constant_scheduler(float(value))) for name, value in pprogram_params.items()]

        self.curriculum.add_param_list(
            param_list
        )
        self.curriculum.plot_all_schedules()

    

        self.generate_X = simulate_X_uniform

        pprogram_batched, pprogram = name2pprogram_maker[gen_config["pprogram"]]

        self.data_generator = GenerateDataCurriculumCFM(
            pprogram_maker = pprogram_batched,
            curriculum= self.curriculum,
            pprogram_covariates = self.generate_X,
        )

        self.epoch_loader = self.data_generator.make_epoch_loader(
            n = N,
            p = P,
            number_of_batches_per_epoch = N_BATCHES_PER_EPOCH,
            n_epochs = N_EPOCHS,
            batch_size= BATCH_SIZE,
            train_frac= float(self.config["BASIC"]["Train_frac"]),
            val_frac= float(self.config["BASIC"]["Val_frac"]),
            shuffle= string2bool(self.config["BASIC"]["Shuffle"]),
            n_samples_to_generate_at_once = int(self.config["BASIC"]["N_samples_to_generate_at_once"]),
        )

        b  = next(iter(self.epoch_loader[0][0])) # try if loader works

        return b 

    def eval(self):
        b_value1 = self.sample_for_value(self.config_param_value1)

        try:
            X1 = b_value1["x"]
            X1 = X1.reshape(X1.shape[0], -1) # flatten the data
            y1 = b_value1["y"]
            D1 = torch.cat([X1, y1], dim=1)

        except:
            D1 = b_value1["x"].reshape(b_value1["x"].shape[0], -1) # flatten the data
        
        b_value2 = self.sample_for_value(self.config_param_value2)

        try:
            X2 = b_value2["x"]
            X2 = X2.reshape(X2.shape[0], -1)
            y2 = b_value2["y"]
            D2 = torch.cat([X2, y2], dim=1)
        except:
            D2 = b_value2["x"].reshape(b_value2["x"].shape[0], -1) # flatten the data 

        d1_indicator = torch.zeros(D1.shape[0])
        d2_indicator = torch.ones(D1.shape[0])

        D = torch.cat([D1, D2], dim=0)
        d_indicator = torch.cat([d1_indicator, d2_indicator], dim=0) 

        randperm = torch.randperm(D.shape[0]) 
        D = D[randperm]
        d_indicator = d_indicator[randperm]  

        # train Rf to distinguish between the two datasets
        rf = RandomForestClassifier()

        D_train = D[:int(D.shape[0]*0.5)]
        d_indicator_train = d_indicator[:int(D.shape[0]*0.5)]
        
        D_test = D[int(D.shape[0]*0.5):]
        d_indicator_test = d_indicator[int(D.shape[0]*0.5):]

        rf.fit(D_train, d_indicator_train)
        
        acc = rf.score(D_test, d_indicator_test)
        
        return acc






